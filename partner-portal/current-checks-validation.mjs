import {transferPeerLossFolder, validateTransferPeerLoss} from '../scripts/qa/transfer-peer-loss-evidence.mjs';
import assert from 'node:assert/strict';

export function validateCurrentChecks(root, content) {
  validatePushCleanup(root);validateReturnPass(root);
  assert.equal(content.flows.find(row=>row.id==='team-conversation').pushInvalidation.source,pushCleanupFolder+'review.json');
  assert.equal(content.flows.find(row=>row.id==='native-startup').foregroundReturnPass.source,returnPassFolder+'review.json');
  for(const folder of [pushCleanupFolder,returnPassFolder])assert(content.updates.some(row=>row.source===folder+'README.md'));
  validateForegroundReturnIntent(root);
  assert.equal(content.flows.find(row=>row.id==='native-startup').foregroundReturnIntent.source,foregroundReturnFolder+'review.json');
  assert(content.updates.some(row=>row.source===foregroundReturnFolder+'README.md'));
  validateTransferPeerLoss(root);
  assert(content.updates.some(row => row.source === transferPeerLossFolder + 'README.md'));
  validateCompressionSecurity(root);
  assert(content.updates.some(row => row.source === compressionSecurityFolder + 'README.md'));
  validateDisconnectRecheck(root);
  assert(content.updates.some(row => row.source === disconnectRecheckFolder + 'README.md'));
  validateSearchDepartureEvidence(root);
  validateSearchDeparturePhone(root);
  validateNativeCopyFollowup(root);
  validateTransferLifecycle(root);
  assert(content.updates.some(row => row.source === transferLifecycleFolder + 'README.md'));
  assert.equal(content.flows.find(row => row.id === 'search').searchDeparturePhone.source, searchDeparturePhoneFolder + 'review.json');
  assert.equal(content.flows.find(row => row.id === 'search').searchDepartureReview.source, searchDepartureFolder + 'review.json');
  assert(content.updates.some(row => row.source === searchDepartureFolder + 'README.md'));
  validateChildBookingReceiptEvidence(root); validateLatestPreparationDiagnostics(root);
  assert.equal(content.flows.find(row => row.id === 'booking').childBookingReceiptRecheck.source, childBookingReceiptFolder + 'services.json');
  assert.equal(content.blockers.find(row => row.id === 'chat-send-stability').lastPassingSource, networkRepeatIdentity.folder + 'README.md');
  assert.equal(content.blockers.find(row => row.id === 'chat-send-stability').transportHistory.source, transferLifecycleFolder + 'README.md');
  assert.equal(content.blockers.find(row => row.id === 'chat-send-stability').captureHistory.source, alertCaptureFailureFolder + 'README.md');
  for (const id of ['chat-send-stability','native-evidence-copy'])
    assert.equal(content.blockers.find(row => row.id === id).samplingHistory.source, notificationSamplingFolder + 'README.md');
  for (const id of ['chat-send-stability','native-evidence-copy']) {
    assert.equal(content.blockers.find(row => row.id === id).latestSource, exitGateFolder + 'README.md');
    assert.equal(content.blockers.find(row => row.id === id).networkPreparationHistory.source, nativeNetworkPreparationFolder + 'README.md');
    assert.equal(content.blockers.find(row => row.id === id).pixelCopyHistory.source, teamPushNativeGateFolder + 'README.md');
    assert.equal(content.blockers.find(row => row.id === id).latestPassingSource, notificationGateFolder + 'README.md');
  }
  validateTeamPushNativeGate(root);
  validateTeamPushNetworkGate(root);
  validateNativeTeamPushSignOut(root);
  validateSignOutConnected(root);
  validateExitGate(root);
  validateSessionExitComponents(root);
  assert.equal(content.flows.find(row => row.id === 'signout').exitComponents.source, sessionExitComponentsFolder + 'review.json');
  assert.equal(content.blockers.find(row => row.id === 'native-evidence-copy').exitLayoutRecheck.source, sessionExitComponentsFolder + 'README.md');
  assert(content.updates.some(row => row.source === exitGateFolder + 'README.md'));
  assert.equal(content.flows.find(row => row.id === 'team-conversation').pushSignOutConnected.source, signOutConnectedFolder + 'review.json');
  assert(content.updates.some(row => row.source === signOutConnectedFolder + 'README.md'));
  assert.equal(content.flows.find(row => row.id === 'team-conversation').pushSignOut.source, nativeTeamPushSignOutFolder + 'review.json');
  for (const folder of [nativeNetworkPreparationFolder, nativeTeamPushSignOutFolder])
    assert(content.updates.some(row => row.source === folder + 'README.md'));
  validateNotificationGate(root);
  validateNotificationSampling(root);
  assert(content.updates.some(row => row.source === notificationSamplingFolder + 'README.md'));
  validateAlertCaptureFailure(root);
  validateReleaseRecheck(root);
  validateCaptureWindowEvidence(root);
  validateTestRunnerSecurity(root);
  validateTlsAgentSecurity(root);
  assert(content.updates.some(row => row.source === tlsAgentSecurityFolder + 'README.md'));
  assert.equal(content.blockers.find(row => row.id === 'dependency-security').latestSource, compressionSecurityFolder + 'README.md');
  validateNativeFollowup(root, content.flows.find(row => row.id === 'team-conversation').nativeRecheck);
  validateNativeFollowupMain(root);
  validateRejectedCaptureProbe(root, content.rejectedCaptureRecheck);
  validateRequestSafetyEvidence(root, content.requestSafetyRecheck);
  validateDependencyPatchEvidence(root, content.dependencyPatchRecheck);
  validateNativeGateRecheck(root, content.nativeGateRecheck);
  validatePublishedMediaSeek(root, content.publishedMediaReview);
  validateBufferedMediaEvidence(root, content.publishedMediaPlayback);
  validateReviewHistoryEvidence(root, content.reviewHistoryRecheck);
  validateReviewPhoneEvidence(root, content.reviewHistoryPhone);
  validateReceivedRatingsEvidence(root, content.receivedRatingsRecheck);
  validateReviewPaginationEvidence(root, content.reviewPaginationRecheck);
  validateReviewDisplayEvidence(root, content.reviewDisplayRecheck);
  validateReviewContextEvidence(root, content.reviewContextRecheck);
  validateReviewBaselineGate(root, content.reviewBaselineGateRecheck);
  validateContextPhoneAttempt(root, content.reviewContextPhoneAttempt);
  validateContextReplayEvidence(root, content.reviewContextPhoneReplay);
  validateReviewRecovery(root, content.reviewSubmissionRecovery);
  validateReviewNetworkPhone(root, content.reviewNetworkPhone);
  validateReviewReceiptPhone(root, content.reviewReceiptPhone);
  validateCaptureLateSampling(root);
  validateBookingReceiptPhone(root, content.flows.find(row => row.id === 'booking').bookingReceiptPhone);
  validateBookingBeforeAck(root, content.flows.find(row => row.id === 'booking').bookingBeforeAckPhone);
}
