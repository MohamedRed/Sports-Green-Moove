import assert from 'node:assert/strict';

export function validateCurrentChecks(root, content) {
  validateSearchDepartureEvidence(root);
  validateSearchDeparturePhone(root);
  validateNativeCopyFollowup(root);
  validateTransferLifecycle(root);
  assert(content.updates.some(row => row.source === transferLifecycleFolder + 'README.md'));
  assert.equal(content.flows.find(row => row.id === 'search').searchDeparturePhone.source, searchDeparturePhoneFolder + 'review.json');
  assert.equal(content.flows.find(row => row.id === 'search').searchDepartureReview.source, searchDepartureFolder + 'review.json');
  assert(content.updates.some(row => row.source === searchDepartureFolder + 'README.md'));
  validateChildBookingReceiptEvidence(root); validateLatestPreparationDiagnostics(root);
  assert.equal(content.flows.find(row => row.id === 'booking').childBookingReceiptRecheck.source, childBookingReceiptFolder + 'services.json');
  assert.equal(content.blockers.find(row => row.id === 'chat-send-stability').lastPassingSource, networkRepeatIdentity.folder + 'README.md');
  assert.equal(content.blockers.find(row => row.id === 'chat-send-stability').latestSource, transferLifecycleFolder + 'README.md');
  validateReleaseRecheck(root);
  validateCaptureWindowEvidence(root);
  validateTestRunnerSecurity(root);
  validateTlsAgentSecurity(root);
  assert(content.updates.some(row => row.source === tlsAgentSecurityFolder + 'README.md'));
  assert.equal(content.blockers.find(row => row.id === 'dependency-security').latestSource, tlsAgentSecurityFolder + 'README.md');
  validateNativeFollowup(root, content.flows.find(row => row.id === 'team-conversation').nativeRecheck);
  validateNativeFollowupMain(root);
  validateRejectedCaptureProbe(root, content.rejectedCaptureRecheck);
  validateRequestSafetyEvidence(root, content.requestSafetyRecheck);
  validateDependencyPatchEvidence(root, content.dependencyPatchRecheck);
  validateNativeGateRecheck(root, content.nativeGateRecheck);
  validatePublishedMediaSeek(root, content.publishedMediaReview);
  validateBufferedMediaEvidence(root, content.publishedMediaPlayback);
  validateReviewHistoryEvidence(root, content.reviewHistoryRecheck);
  validateReviewPhoneEvidence(root, content.reviewHistoryPhone);
  validateReceivedRatingsEvidence(root, content.receivedRatingsRecheck);
  validateReviewPaginationEvidence(root, content.reviewPaginationRecheck);
  validateReviewDisplayEvidence(root, content.reviewDisplayRecheck);
  validateReviewContextEvidence(root, content.reviewContextRecheck);
  validateReviewBaselineGate(root, content.reviewBaselineGateRecheck);
  validateContextPhoneAttempt(root, content.reviewContextPhoneAttempt);
  validateContextReplayEvidence(root, content.reviewContextPhoneReplay);
  validateReviewRecovery(root, content.reviewSubmissionRecovery);
  validateReviewNetworkPhone(root, content.reviewNetworkPhone);
  validateReviewReceiptPhone(root, content.reviewReceiptPhone);
  validateCaptureLateSampling(root);
  validateBookingReceiptPhone(root, content.flows.find(row => row.id === 'booking').bookingReceiptPhone);
  validateBookingBeforeAck(root, content.flows.find(row => row.id === 'booking').bookingBeforeAckPhone);
}
